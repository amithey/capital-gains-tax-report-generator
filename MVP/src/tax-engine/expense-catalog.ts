export type ExpenseKind =
  /** מוכרת במלואה כשהיא עסקית. */
  | "full"
  /** מוכרת בשיעור קבוע בתקנות (למשל רכב). */
  | "capped"
  /** מוכרת לפי החלק היחסי של השימוש העסקי (המשתמש קובע אחוז). */
  | "proportional";

export interface ExpenseCategory {
  readonly id: string;
  /** שם הקטגוריה בעברית. */
  readonly label: string;
  /** הסבר בעברית פשוטה: מה זה ולמה זה מוכר. */
  readonly explanation: string;
  /** מתי ההוצאה מוכרת ומתי לא. */
  readonly whenRecognized: string;
  /** אילו מסמכים לשמור. */
  readonly documentation: string;
  readonly kind: ExpenseKind;
  /**
   * שיעור ההכרה (0..1). ל-full זה 1; ל-capped זה השיעור הקבוע;
   * ל-proportional זו ברירת מחדל שהמשתמש יכול לשנות (businessUsePercent).
   */
  readonly recognizedShare: number;
}

